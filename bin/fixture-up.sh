#!/usr/bin/env bash
# Brings up the local fixture: site on :8080, a separate "CDN" origin on :8081.
# Two origins, so cross-origin third-party detection is genuinely exercised.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"
mkdir -p .audit-raw

# Credential-shaped fixtures are generated, never committed. Every value is
# synthetic and non-functional; the AWS one is that vendor's own published
# documentation example.
#
# The fragments are concatenated rather than written whole so that THIS file --
# which is committed -- contains no complete credential-shaped literal. Only
# the generated output does, and that is gitignored. A repo that ships eight
# fake keys trains everyone to ignore exactly the pattern we are hunting.
s_pub="pk_""live_FIXTUREpublishable0000000000"
s_stripe="sk_""test_FIXTURE00000000000000000000"
s_aws="AKIA""IOSFODNN7EXAMPLE"
s_cg="CG-""FIXTUREdemokey00000000"
s_jwt="eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9"".eyJzdWIiOiJmaXh0dXJlIn0"".FIXTUREsignaturevalue000000"
s_dsn="https://fixture00000000000000000000000@o0.ingest.sentry.io/0"
s_generic="fixture_generic_secret_value_1234567890"

cat > fixture/site/assets/config.gen.js <<EOF
/* GENERATED BY bin/fixture-up.sh -- synthetic values, gitignored, never real. */
window.__APP_CONFIG = {
  env: "production",
  stripePublishableKey: "$s_pub",
  stripeSecretKey: "$s_stripe",
  awsAccessKeyId: "$s_aws",
  coingeckoApiKey: "$s_cg",
  sessionToken: "$s_jwt",
  sentryDsn: "$s_dsn",
  apiSecret: "$s_generic"
};
EOF

start() { # port, dir, name
  if curl -s -o /dev/null --max-time 2 "http://127.0.0.1:$1/" 2>/dev/null; then
    echo "  $3 already up on :$1"; return
  fi
  nohup python3 -m http.server "$1" --bind 127.0.0.1 --directory "$2" \
    > ".audit-raw/$3.log" 2>&1 &
  echo $! > ".audit-raw/$3.pid"
  echo "  $3 -> http://127.0.0.1:$1 (pid $!)"
}

echo "Starting fixture servers:"
start 8080 fixture/site site
start 8081 fixture/cdn cdn

for i in $(seq 1 25); do
  if curl -sf -o /dev/null --max-time 1 http://localhost:8080/index.html \
     && curl -sf -o /dev/null --max-time 1 http://127.0.0.1:8081/widget.js; then
    echo "Fixture ready."; exit 0
  fi
  sleep 0.2
done
echo "FAILED: fixture did not become ready in 5s" >&2
exit 1
